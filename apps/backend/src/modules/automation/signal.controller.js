/**
 * SIGNAL CONTROLLER — External webhook for Temporal workflow signals.
 *
 * Handles the public endpoint that approve/reject links point to.
 * When a human clicks the link from an email or Slack message, this
 * controller connects to the Temporal Client and fires the signal
 * into the sleeping workflow.
 *
 * Endpoint: POST /api/automations/signal/:workflowId
 * Also:     GET  /api/automations/signal/:workflowId (for clickable email links)
 *
 * Query params or body:
 *   nodeId  — The approval node ID to unblock
 *   status  — "approved" | "rejected"
 *   email   — (optional) Reviewer's email for audit trail
 *   comment — (optional) Reviewer's comment
 *
 * Security: The workflowId itself is the capability token. It is a UUID
 * generated by Temporal that is not guessable. The notification activity
 * only sends it to the configured recipient.
 */

import { getTemporalClient, TASK_QUEUE } from "../../temporal/client.js";

const VALID_STATUSES = new Set(["approved", "rejected"]);

/**
 * Handle an incoming approval/rejection signal.
 * Supports both GET (email link click) and POST (API / Slack interactive).
 */
export async function handleApprovalSignal(req, res) {
  try {
    const { workflowId } = req.params;

    if (!workflowId) {
      return res.status(400).json({ error: "Missing workflowId in URL." });
    }

    // Merge query params (GET) and body (POST) — query takes precedence
    // so email links work with a single GET click.
    const params = { ...req.body, ...req.query };

    const nodeId = params.nodeId;
    const status = params.status;
    const reviewerEmail = params.email || null;
    const comment = params.comment || null;

    if (!nodeId) {
      return res.status(400).json({ error: "Missing required param: nodeId" });
    }
    if (!VALID_STATUSES.has(status)) {
      return res.status(400).json({
        error: `Invalid status "${status}". Must be "approved" or "rejected".`,
      });
    }

    // Connect to Temporal and fire the signal into the running workflow
    const client = await getTemporalClient();
    const handle = client.workflow.getHandle(workflowId);

    await handle.signal("approvalSignal", {
      nodeId,
      status,
      reviewerEmail,
      comment,
    });

    // For GET requests (email link clicks), return a user-friendly HTML page
    if (req.method === "GET") {
      const isApproved = status === "approved";
      const color = isApproved ? "#22c55e" : "#ef4444";
      const icon = isApproved ? "\u2705" : "\u274c";
      const label = isApproved ? "Approved" : "Rejected";
      const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

      return res.status(200).send(`
        <!DOCTYPE html>
        <html>
        <head>
          <meta charset="utf-8">
          <meta name="viewport" content="width=device-width, initial-scale=1">
          <title>BlinkBox — ${label}</title>
          <style>
            body {
              font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', sans-serif;
              display: flex; align-items: center; justify-content: center;
              min-height: 100vh; margin: 0; background: #fafafa;
            }
            .card {
              text-align: center; padding: 48px; background: white;
              border-radius: 12px; box-shadow: 0 2px 12px rgba(0,0,0,0.08);
              max-width: 400px;
            }
            .icon { font-size: 48px; margin-bottom: 16px; }
            h1 { color: ${color}; margin: 0 0 8px; font-size: 24px; }
            p { color: #666; margin: 0; font-size: 15px; }
            .meta { margin-top: 24px; font-size: 12px; color: #aaa; }
          </style>
        </head>
        <body>
          <div class="card">
            <div class="icon">${icon}</div>
            <h1>${label}</h1>
            <p>Your decision has been recorded. The workflow will continue.</p>
            <p class="meta">Workflow: ${esc(workflowId)}<br>Node: ${esc(nodeId)}</p>
          </div>
        </body>
        </html>
      `);
    }

    // For POST requests (API calls), return JSON
    return res.status(200).json({
      success: true,
      workflowId,
      nodeId,
      status,
      message: `Signal delivered: ${status}`,
    });
  } catch (err) {
    const message = err.message || "Unknown error";

    // Temporal throws specific errors for workflows that don't exist or already completed
    if (message.includes("not found") || message.includes("NOT_FOUND")) {
      return res.status(404).json({
        error: "Workflow not found. It may have already completed or timed out.",
      });
    }

    console.error("[Signal Controller] Error:", message);
    return res.status(500).json({
      error: "Failed to deliver approval signal.",
    });
  }
}
