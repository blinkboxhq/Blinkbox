import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { derive } from "./nodeCatalog.derive.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, "../src/nodes/nodeCatalog.js");

const { nodes } = derive();

const banner = `// GENERATED by scripts/generate-node-catalog.mjs — do not edit by hand.
// Run \`npm run catalog\` after changing nodeRegistry.js, triggerVariants.js,
// AgentPicker.jsx or the backend node registry. nodeCatalog.test.js fails on drift.
//
// Only nodes reachable from a picker appear here: the connector and Brian must
// never build a workflow out of something the user cannot see or edit in the UI.
//   pickers    — which picker surfaces the node ("action" | "trigger" | "agent")
//   executable — a backend handler exists; false means canvas-only, unbuildable
//   documented — brian.nodes.js carries its config field schema
`;

const lines = nodes.map((n) => `  ${JSON.stringify(n)},`).join("\n");

const body = `${banner}
export const PICKER_NODES = [
${lines}
];

const BY_KEY = new Map(PICKER_NODES.map((n) => [n.key, n]));

export function isPickerNode(key) {
  return BY_KEY.has(key);
}

export function getPickerNode(key) {
  return BY_KEY.get(key) || null;
}

export function listPickerNodes({ picker, category, buildableOnly = false } = {}) {
  return PICKER_NODES.filter(
    (n) =>
      (!picker || n.pickers.includes(picker)) &&
      (!category || n.category === category) &&
      (!buildableOnly || n.executable),
  );
}

export const BUILDABLE_KEYS = new Set(
  PICKER_NODES.filter((n) => n.executable).map((n) => n.key),
);
`;

fs.writeFileSync(OUT, body);
const stats = {
  total: nodes.length,
  action: nodes.filter((n) => n.pickers.includes("action")).length,
  trigger: nodes.filter((n) => n.pickers.includes("trigger")).length,
  agent: nodes.filter((n) => n.pickers.includes("agent")).length,
  executable: nodes.filter((n) => n.executable).length,
  documented: nodes.filter((n) => n.documented).length,
  integrations: nodes.filter((n) => n.integration).length,
};
console.log(`wrote ${path.relative(process.cwd(), OUT)}`);
console.table(stats);
