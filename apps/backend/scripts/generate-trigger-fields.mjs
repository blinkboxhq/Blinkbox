import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { deriveTriggerFields } from "./triggerFields.derive.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, "../src/nodes/triggerFields.js");

const { triggers, unmapped } = await deriveTriggerFields();

const banner = `// GENERATED by scripts/generate-trigger-fields.mjs — do not edit by hand.
// Run \`npm run catalog\` after changing triggerEvents.js or triggerVariants.js.
// triggerFields.test.js fails on drift.
//
// Keyed by node key (backendType). Per trigger:
//   fields — panel fields every event of this trigger shows
//   events — the legal event ids, each with the exact config skeleton the
//            frontend writes when it is picked, plus any event-only fields
//   out    — the \`$trigger.*\` variables the event payload exposes
`;

const entries = Object.entries(triggers)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([key, t]) => `  ${JSON.stringify(key)}: ${JSON.stringify(t)},`)
  .join("\n");

fs.writeFileSync(
  OUT,
  `${banner}
export const TRIGGER_FIELDS = {
${entries}
};

export function getTriggerFields(key) {
  return TRIGGER_FIELDS[key] || null;
}
`,
);

const keys = Object.keys(triggers);
console.log(
  `triggerFields.js — ${keys.length} triggers, ` +
    `${keys.reduce((n, k) => n + triggers[k].events.length, 0)} events, ` +
    `${keys.filter((k) => triggers[k].out.length).length} with output vars`,
);
if (unmapped.length) console.log(`no backendType in triggerVariants.js: ${unmapped.join(", ")}`);
