import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { deriveOperationParams } from "./operationParams.derive.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, "../src/nodes/operationParams.js");

const { params, stats } = await deriveOperationParams();

const banner = `// GENERATED by scripts/generate-operation-params.mjs — do not edit by hand.
// Run \`npm run catalog\` after changing anything under src/nodes/_packaged.
// operationParams.test.js fails on drift.
//
// The config keys each integration operation reads, derived from the handlers
// themselves — only a handful of the packaged apps declare \`params\` by hand.
// Keyed by node type, then operation, then key:
//   t — the type the handler's own use of the value implies (absent = unknown)
//   r — the handler refuses to run without it
//
// Nothing here is invented: a key is listed only because some handler reads it.
// Derivation can miss a key it cannot see statically, so this narrows the
// passthrough config; it never replaces it.
`;

const entries = Object.entries(params)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([type, ops]) => `  ${JSON.stringify(type)}: ${JSON.stringify(ops)},`)
  .join("\n");

fs.writeFileSync(
  OUT,
  `${banner}
export const OPERATION_PARAMS = {
${entries}
};

export function getOperationParams(type, operation) {
  return OPERATION_PARAMS[type]?.[operation] || null;
}
`,
);

console.log(
  `operationParams.js — ${stats.apps} apps, ${stats.ops} operations, ${stats.typed} with params`,
);
